function formatPlanCheckForSharing() {
  const dayLines = planCheckDays
    .map((stops, i) => `Day ${i + 1}: ${stops.length ? stops.join(" -> ") : "(no stops added)"}`)
    .join("\n");
  const notes = planCheckNotes.trim();
  let aiCheck = "";
  if (planCheckResult && planCheckResult.raw) {
    aiCheck = planCheckResult.raw.trim();
  } else if (planCheckResult) {
    const tag = (v) => (v === "good" ? "looks good" : "worth another look");
    aiCheck = planCheckResult.days
      .map((d, i) => {
        const lines = [`Day ${i + 1} (~${d.walkingKm} km, ~${d.kcal} kcal)`];
        (d.stops || []).forEach((st, si) => {
          const kw = st.keywords && st.keywords.length ? ` [${st.keywords.join(", ")}]` : "";
          lines.push(`  ${planCheckDays[i] ? planCheckDays[i][si] : "Stop"}${kw} - ${tag(st.verdict)}: ${st.feedback}`);
          const leg = (d.legs || [])[si];
          if (leg && si < (d.stops || []).length - 1) lines.push(`    -> next: ${tag(leg.verdict)}: ${leg.feedback}`);
        });
        return lines.join("\n");
      })
      .join("\n");
    if (planCheckResult.keywords && planCheckResult.keywords.length) aiCheck += `\nPlan vibe: ${planCheckResult.keywords.join(", ")}`;
    if (planCheckResult.summary) aiCheck += `\n${planCheckResult.summary}`;
    if (planCheckResult.totalKcal) aiCheck += `\nTotal: ~${planCheckResult.totalKcal} kcal`;
  }
  let text = dayLines;
  if (notes) text += `\n\nNotes: ${notes}`;
  if (aiCheck) text += `\n\nAI Check: ${aiCheck}`;
  return text;
}

async function shareMyPlan() {
  if (!currentUser) {
    openAuthModal("signin");
    return;
  }
  const hasAnyStops = planCheckDays.some((d) => d.length > 0);
  if (!hasAnyStops) return;
  sharePlanLoading = true;
  sharePlanError = null;
  render();
  try {
    const fit = evaluateFit(selectedHotel, selectedTheme);
    const username = currentUser.user_metadata && currentUser.user_metadata.username ? currentUser.user_metadata.username : currentUser.email;
    await sharePlanPublicly(currentUser.id, username, {
      hotelName: selectedHotel.name,
      city: selectedHotel.city,
      themeKey: selectedTheme,
      score: fit.score,
      planText: formatPlanCheckForSharing(),
    });
    sharePlanSuccess = true;
  } catch (e) {
    sharePlanError = e.message || "Couldn't share your plan.";
  }
  sharePlanLoading = false;
  render();
}

