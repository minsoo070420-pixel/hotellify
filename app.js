    leg ? `<div class="feedback-card feedback-leg ${verdictClass(leg.verdict)}"><div class="feedback-text">${leg.verdict === "good" ? "✅" : "⚠️"} ${escapeHtml(leg.feedback || "")}</div></div>` : "";

