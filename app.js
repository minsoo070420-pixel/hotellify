function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-+|-+$)/g, "") || "hotel";
}

function wrapCenteredText(ctx, text, x, y, maxWidth, lineHeight, maxLines) {
  const words = text.split(" ");
  let line = "";
  const lines = [];
  for (let n = 0; n < words.length; n++) {
    const testLine = line + words[n] + " ";
    if (ctx.measureText(testLine).width > maxWidth && n > 0) {
      lines.push(line.trim());
      line = words[n] + " ";
    } else {
      line = testLine;
    }
  }
  lines.push(line.trim());
  const clipped = maxLines ? lines.slice(0, maxLines) : lines;
  clipped.forEach((l, i) => ctx.fillText(l, x, y + i * lineHeight));
  return clipped.length;
}

function drawShareLogo(ctx, x, y, size) {
  const scale = size / 32;
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(scale, scale);
  const grad = ctx.createLinearGradient(4, 6, 28, 26);
  grad.addColorStop(0, "#4ade80");
  grad.addColorStop(1, "#047857");
  ctx.strokeStyle = grad;
  ctx.lineWidth = 2.75;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  ctx.beginPath();
  ctx.moveTo(5, 17);
  ctx.lineTo(16, 6);
  ctx.lineTo(27, 17);
  ctx.stroke();
  ctx.beginPath();
  ctx.moveTo(10, 19.5);
  ctx.lineTo(10, 26);
  ctx.stroke();
  ctx.beginPath();
  ctx.moveTo(22, 19.5);
  ctx.lineTo(22, 26);
  ctx.stroke();
  ctx.beginPath();
  ctx.moveTo(8, 26);
  ctx.lineTo(24, 26);
  ctx.stroke();
  ctx.restore();
}

